async function main() {
  console.log(`[seed] Starting seed of 10 Timis demo arenas...`);

  let updatedCount = 0;
  let createdCount = 0;

  for (const item of TEN_DEMO_ARENAS) {
    const { matchNames, ...data } = item;

    // Look for existing venue matching any of the candidate names
    const existing = await prisma.venue.findFirst({
      where: {
        name: { in: matchNames },
      },
    });

    if (existing) {
      await prisma.venue.update({
        where: { id: existing.id },
        data: {
          name: data.name,
          location: data.location,
          county: data.county,
          status: data.status,
          address: data.address,
          specs: data.specs,
          sport: data.sport,
          surface: data.surface,
          capacity: data.capacity,
          floodlights: data.floodlights,
          pricePerHour: data.pricePerHour,
          phone: data.phone,
          website: data.website,
          googleMapsUrl: data.googleMapsUrl,
          rating: data.rating,
          reviewCount: data.reviewCount,
          crmStatus: data.crmStatus,
          imageUrl: data.imageUrl,
          galleryImages: data.galleryImages,
          isDemo: true,
          isActive: true,
        },
      });
      console.log(`✓ Updated: ${data.name} (ID: ${existing.id})`);
      updatedCount++;
    } else {
      const created = await prisma.venue.create({
        data: {
          ...data,
          isDemo: true,
          isActive: true,
        },
      });
      console.log(`+ Created: ${data.name} (ID: ${created.id})`);
      createdCount++;
    }
  }

  console.log(`[seed] Finished: ${createdCount} created, ${updatedCount} updated.`);
}

main()
  .catch((err) => {
    console.error("Error running seed script:", err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
